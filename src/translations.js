export function isTranslationKey(key) {
  return Object.prototype.hasOwnProperty.call(messages.en, key);
}

export function translateKey(key, language, values = {}) {
  const message = messages[language]?.[key] || messages.en[key] || key;
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder
  ));
}

export function translatePlural(key, count, language) {
  const pluralRule = new Intl.PluralRules(language === "sw" ? "sw-TZ" : language).select(count);
  const suffix = pluralRule === "one" ? "one" : "other";
  return translateKey(`${key}.${suffix}`, language, { count: formatNumber(count, language) });
}

export function formatNumber(value, language) {
  const locale = language === "fr" ? "fr-FR" : language === "en" ? "en-TZ" : "sw-TZ";
  return new Intl.NumberFormat(locale, { maximumFractionDigits: 2 }).format(Number(value) || 0);
}

export function formatDate(value, language, options = {}) {
  const date = value instanceof Date ? value : new Date(value);
  if (!Number.isFinite(date.getTime())) return "—";
  const locale = language === "fr" ? "fr-FR" : language === "en" ? "en-TZ" : "sw-TZ";
  return new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "Africa/Dar_es_Salaam",
    ...options,
  }).format(date);
}
