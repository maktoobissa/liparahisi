export function translate(text, language) {
  const phrase = String(text).trim();
  return translations[phrase]?.[language] || text;
}

function localizeNode(node, language) {
  if (typeof node === "string") {
    const trimmed = node.trim();
    return trimmed ? node.replace(trimmed, translate(trimmed, language)) : node;
  }
  if (Array.isArray(node)) return node.map((child) => localizeNode(child, language));
  if (!React.isValidElement(node)) return node;
  if (node.props["data-no-translate"]) return node;

  const props = {};
  for (const name of ["aria-label", "alt", "placeholder", "title"]) {
    if (typeof node.props[name] === "string") {
      props[name] = translate(node.props[name], language);
    }
  }
  return React.cloneElement(node, props, localizeNode(node.props.children, language));
}

export function useLocalize() {
  const { language } = useContext(languageContext);
  return useCallback((node) => localizeNode(node, language), [language]);
}

export function useLanguage() {
  return useContext(languageContext);
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      const saved = window.localStorage.getItem(languageStorageKey);
      return supportedLanguages.includes(saved) ? saved : "sw";
    } catch {
      return "sw";
    }
  });

  const setLanguage = useCallback((nextLanguage) => {
    setLanguageState(nextLanguage);
    try {
      window.localStorage.setItem(languageStorageKey, nextLanguage);
    } catch (error) {
      console.error("Could not save language preference.", error);
    }
  }, []);

  useEffect(() => {
    const htmlLanguage = language === "sw" ? "sw-TZ" : language;
    document.documentElement.lang = htmlLanguage;
    document.title = language === "en"
      ? "LipaRahisi — Pay, Send, Receive"
      : language === "fr"
        ? "LipaRahisi — Payer, Envoyer, Recevoir"
        : "LipaRahisi — Lipa, Tuma, Pokea";
    const description = document.querySelector('meta[name="description"]');
    if (description) {
      description.content = language === "en"
        ? "LipaRahisi — pay, send, and receive payments with ease."
        : language === "fr"
          ? "LipaRahisi — payez, envoyez et recevez des paiements facilement."
          : "LipaRahisi — Lipa, Tuma, Pokea. Malipo na biashara kwa urahisi.";
    }
  }, [language]);

  return (
    <languageContext.Provider value={{ language, setLanguage }}>
      {children}
    </languageContext.Provider>
  );
}
